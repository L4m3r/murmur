import {queryRequest} from './http-query.mjs';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const base=process.env.BASE_URL||'http://127.0.0.1:9876';
const auth=process.env.API_TOKEN?{authorization:`Bearer ${process.env.API_TOKEN}`} : {};
async function query(sql,expected=200){
  const result=await queryRequest(base,{sql,idempotencyKey:randomUUID()},{headers:auth,expected});
  assert.equal(result.status,expected,`${sql.slice(0,150)}: ${JSON.stringify(result.body)}`);return result.body;
}
const rows=result=>result.results.at(-1).rows;
const stamp=Date.now().toString(36), table=`ordered_${stamp}`;
await query(`CREATE TABLE ${table} (id INTEGER PRIMARY KEY, score REAL, pad TEXT)`);
const loaded=await query(`INSERT INTO ${table} (id,score,pad) VALUES `+Array.from({length:64},(_,i)=>`(${i-32},${i<40?7:100+i},'${'p'.repeat(96)}')`).join(','));
const tablets=loaded.routing.find(route=>route.table===table).tablets;
assert.ok(tablets.length>1);
assert.equal(tablets[0].start,null);assert.equal(tablets.at(-1).end,null);
for(let i=1;i<tablets.length;i++)assert.equal(tablets[i].start,tablets[i-1].end);
const small=await query(`SELECT id FROM ${table} WHERE id >= -3 AND id < 3 ORDER BY id`);
assert.deepEqual(rows(small),[-3,-2,-1,0,1,2].map(id=>({id})));
assert.equal(small.plan.type,'primary-range');
assert.ok(small.plan.tabletsVisited<small.plan.tabletsTotal,JSON.stringify(small.plan));
assert.equal(small.plan.rowsRead,6,'range storage.list must not load unrelated rows');
console.log('PASS ordered numeric range visits fewer tablets and reads exactly six matching row keys');
const pivot=tablets[1].start;
for(const [op,expected] of [['>=',Array.from({length:64},(_,i)=>i-32).filter(id=>id>=pivot)],['>',Array.from({length:64},(_,i)=>i-32).filter(id=>id>pivot)],['<=',Array.from({length:64},(_,i)=>i-32).filter(id=>id<=pivot)],['<',Array.from({length:64},(_,i)=>i-32).filter(id=>id<pivot)]]){
  assert.deepEqual(rows(await query(`SELECT id FROM ${table} WHERE id ${op} ${pivot} ORDER BY id`)),expected.map(id=>({id})));
}
assert.deepEqual(rows(await query(`SELECT id FROM ${table} WHERE id >= ${pivot} AND id <= ${pivot}`)),[{id:pivot}]);
const contradictory=await query(`SELECT id FROM ${table} WHERE id > 5 AND id < -5`);
assert.deepEqual(rows(contradictory),[]);assert.equal(contradictory.plan.rowsRead,0);
console.log('PASS inclusive/exclusive bounds at actual tablet pivot and contradictory range pruning');
await query(`CREATE INDEX by_score ON ${table}(score)`);
const duplicates=await query(`SELECT id FROM ${table} WHERE score = 7 ORDER BY id`);
assert.deepEqual(rows(duplicates),Array.from({length:40},(_,i)=>({id:i-32})));
assert.equal(duplicates.plan.type,'index-range');
assert.ok(duplicates.plan.indexTabletsTotal>1);
assert.ok(duplicates.plan.indexTabletsVisited>1,'duplicate value prefix must cross backing tablet boundaries');
assert.equal(duplicates.plan.rowsRead,40);
assert.equal(duplicates.plan.rowsFetched,40);
const indexRange=await query(`SELECT id FROM ${table} WHERE score >= 145 AND score < 148 ORDER BY id`);
assert.deepEqual(rows(indexRange),[13,14,15].map(id=>({id})));
assert.equal(indexRange.plan.rowsRead,3);
assert.ok(indexRange.plan.indexTabletsVisited<indexRange.plan.indexTabletsTotal);
console.log('PASS composite (value,PK) index prefix spans duplicate split groups; bounded index scan reads only matches');
await query(`INSERT INTO ${table}(id,score,pad) VALUES (100,NULL,''),(101,NULL,'')`);
const nullExcluded=await query(`SELECT id FROM ${table} WHERE score < 0`);
assert.deepEqual(rows(nullExcluded),[]);assert.equal(nullExcluded.plan.rowsRead,0);
console.log('PASS nullable index entries are excluded from SQL numeric range at storage bounds');
const decimal=`decimal_${stamp}`;
await query(`CREATE TABLE ${decimal} (id REAL PRIMARY KEY); INSERT INTO ${decimal}(id) VALUES (-10.5),(-0.5),(0),(0.25),(1.5),(10.75)`);
assert.deepEqual(rows(await query(`SELECT id FROM ${decimal} WHERE id > -0.5 AND id <= 1.5 ORDER BY id`)),[{id:0},{id:0.25},{id:1.5}]);
console.log('PASS negative, zero and positive decimal primary-key ranges');
const unicode=`unicode_${stamp}`;
await query(`CREATE TABLE ${unicode} (id TEXT PRIMARY KEY); INSERT INTO ${unicode}(id) VALUES ('😀'),(''),('A'),('é'),('中')`);
assert.deepEqual(rows(await query(`SELECT id FROM ${unicode} WHERE id >= '' ORDER BY id`)),[{id:''},{id:'😀'}]);
assert.deepEqual(rows(await query(`SELECT id FROM ${unicode} WHERE id < '😀' ORDER BY id`)),['A','é','中',''].map(id=>({id})));
console.log('PASS UTF-8 text ordering places U+E000 before astral emoji in predicates and storage');
const boolean=`boolean_${stamp}`;
await query(`CREATE TABLE ${boolean} (id BOOLEAN PRIMARY KEY); INSERT INTO ${boolean}(id) VALUES (true),(false)`);
assert.deepEqual(rows(await query(`SELECT id FROM ${boolean} WHERE id >= false AND id < true ORDER BY id`)),[{id:false}]);
assert.deepEqual(rows(await query(`SELECT id FROM ${boolean} WHERE id = true`)),[{id:true}]);
console.log('PASS BOOLEAN primary-key range and equality');
console.log('7 ordered-range integration tests passed');
